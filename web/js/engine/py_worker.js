/*
 * py_worker.js — runs Python (Pyodide) in a background thread (Web Worker).
 *
 * WHAT IT DOES
 *   Running Python in a worker keeps the page responsive during long
 *   calculations (Monte Carlo, κ_intr fitting). On "init" it
 *     1. loads Pyodide (local copy first, CDN if the local copy is missing),
 *     2. loads numpy,
 *     3. unpacks py/solubility_toolkit.zip and py/web_api.py into Python,
 *   then answers "call" messages by running web_api.call(name, args).
 *
 * MESSAGES
 *   page -> worker : { id, cmd: "init", base, config }      config = PYODIDE in js/config.js
 *                    { id, cmd: "call", fn, args }
 *   worker -> page : { id, ok: true, result } | { id, ok: false, error }
 *                    { status: "text" }                      progress while loading
 *                    { progress: { done, total } }           progress of a long calculation (κ fit)
 *
 * HOW TO CHANGE
 *   You normally do not edit this file. Versions and paths: js/config.js.
 *   New calculations: py/web_api.py. Talk to this worker through PyEngine.js.
 */
let pyodide = null;
let api = null;
let source = null;

const status = (text) => self.postMessage({ status: text });

async function loadRuntime(base, config) {
  const candidates = [
    { name: "local", url: new URL(config.local, base).href },
    { name: "cdn", url: config.cdn },
  ];
  let lastError = null;
  for (const c of candidates) {
    try {
      const mod = await import(c.url + "pyodide.mjs");
      const py = await mod.loadPyodide({ indexURL: c.url });
      source = c.name;
      return py;
    } catch (err) {
      lastError = err;
    }
  }
  throw new Error("Could not load Pyodide (local copy or CDN): " + lastError);
}

async function fetchOk(url, kind) {
  const res = await fetch(url, { cache: "no-cache" });
  if (!res.ok) throw new Error(`Could not load ${url} (HTTP ${res.status})`);
  return kind === "text" ? res.text() : res.arrayBuffer();
}

async function init(base, config) {
  status("Loading Python…");
  pyodide = await loadRuntime(base, config);

  status("Loading numpy…");
  await pyodide.loadPackage(config.packages);

  status("Loading toolkit…");
  const sitePackages = pyodide.runPython("import site; site.getsitepackages()[0]");
  const zip = await fetchOk(new URL(config.toolkit_zip, base).href, "buffer");
  pyodide.unpackArchive(zip, "zip", { extractDir: sitePackages });
  const apiSource = await fetchOk(new URL(config.web_api, base).href, "text");
  pyodide.FS.writeFile(`${sitePackages}/web_api.py`, apiSource);
  api = pyodide.pyimport("web_api");
  // long calculations report how far they are (web_api.progress_hook is called from Python)
  api.progress_hook = (done, total) => self.postMessage({ progress: { done, total } });

  return { source, pyodide: pyodide.version, ...JSON.parse(api.call("version", "{}")) };
}

self.onmessage = async (event) => {
  const { id, cmd, base, config, fn, args } = event.data;
  try {
    let result;
    if (cmd === "init") {
      result = await init(base, config);
    } else if (cmd === "call") {
      if (!api) throw new Error("Python engine is not ready");
      result = JSON.parse(api.call(fn, JSON.stringify(args || {})));
    } else {
      throw new Error(`unknown command: ${cmd}`);
    }
    self.postMessage({ id, ok: true, result });
  } catch (err) {
    // keep the last line of a Python traceback: that is the readable message
    const text = String(err && err.message ? err.message : err).trim();
    const last = text.split("\n").pop().replace(/^\w+(Error|Exception):\s*/, "");   // "ValueError: …" -> "…"
    self.postMessage({ id, ok: false, error: last, detail: text });
  }
};
