/*
 * PyEngine.js — the page's handle on the Python engine.
 *
 * WHAT IT DOES
 *   Starts py_worker.js once and gives the pages one simple method:
 *
 *       const result = await engine.call("kernel_curves", { vr: [1.78, 0.32], bin_centers: [-1, 0] });
 *
 *   "kernel_curves" is a method of WebApi in py/web_api.py; the arguments and
 *   the result are plain JSON.
 *
 *   Long calculations (the κ fit) report progress:  engine.onProgress((done, total) => …)
 *   and can be stopped:  engine.restart()  — Python cannot be interrupted in the middle of a
 *   calculation, so this throws the engine away and loads a fresh one (a few seconds).
 *   The call that was running fails with an Error whose .cancelled is true. The engine also reports its state
 *   ("loading" | "ready" | "error") for the status pill in the header.
 *
 * HOW TO CHANGE
 *   You normally do not edit this file.
 *   Paths / Pyodide version -> js/config.js.   New calculations -> py/web_api.py.
 */
import { PYODIDE } from "../config.js";

export class PyEngine {
  constructor(config = PYODIDE) {
    this.config = config;
    this.state = "idle";          // idle | loading | ready | error
    this.detail = "";             // progress text or error message
    this.info = null;             // { source, pyodide, toolkit, numpy } once ready
    this._listeners = new Set();
    this._progress = new Set();
    this._pending = new Map();
    this._nextId = 1;
    this._ready = null;
  }

  /** Start loading (safe to call many times). Resolves with version info. */
  start() {
    if (this._ready) return this._ready;
    this._set("loading", "Starting…");
    this.worker = new Worker(new URL("./py_worker.js", import.meta.url), { type: "module" });
    this.worker.onmessage = (e) => this._onMessage(e.data);
    this.worker.onerror = (e) => this._failAll(e.message || "Python worker crashed");
    this._ready = this._send({ cmd: "init", base: document.baseURI, config: this.config })
      .then((info) => {
        this.info = info;
        this._set("ready", "");
        return info;
      })
      .catch((err) => {
        this._set("error", err.message);
        throw err;
      });
    return this._ready;
  }

  /** Call a WebApi method in Python. Waits for the engine if it is still loading. */
  async call(fn, args = {}) {
    await this.start();
    return this._send({ cmd: "call", fn, args });
  }

  /** cb(done, total) while a long calculation runs. Returns a function that unsubscribes. */
  onProgress(cb) {
    this._progress.add(cb);
    return () => this._progress.delete(cb);
  }

  /** Stop whatever is running and load a fresh engine. Pages keep their inputs and results. */
  restart() {
    if (this.worker) this.worker.terminate();
    for (const p of this._pending.values()) p.reject(Object.assign(new Error("Cancelled"), { cancelled: true }));
    this._pending.clear();
    this._ready = null;
    return this.start();
  }

  /** cb(state, detail) now and on every change. Returns a function that unsubscribes. */
  onStatus(cb) {
    this._listeners.add(cb);
    cb(this.state, this.detail);
    return () => this._listeners.delete(cb);
  }

  // ------------------------------------------------------------ internals
  _send(message) {
    const id = this._nextId++;
    return new Promise((resolve, reject) => {
      this._pending.set(id, { resolve, reject });
      this.worker.postMessage({ id, ...message });
    });
  }

  _onMessage(msg) {
    if (msg.status !== undefined) {
      if (this.state === "loading") this._set("loading", msg.status);
      return;
    }
    if (msg.progress !== undefined) {
      for (const cb of this._progress) cb(msg.progress.done, msg.progress.total);
      return;
    }
    const p = this._pending.get(msg.id);
    if (!p) return;
    this._pending.delete(msg.id);
    if (msg.ok) p.resolve(msg.result);
    else p.reject(Object.assign(new Error(msg.error), { detail: msg.detail }));
  }

  _failAll(text) {
    for (const p of this._pending.values()) p.reject(new Error(text));
    this._pending.clear();
    this._set("error", text);
  }

  _set(state, detail) {
    this.state = state;
    this.detail = detail;
    for (const cb of this._listeners) cb(state, detail);
  }
}

/** The one engine shared by all pages. */
export const engine = new PyEngine();
